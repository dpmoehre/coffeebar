export function groupByDate(entries = CHANGELOG) {
  const groups = [];
  const seen = new Map();
  for (const entry of entries) {
    let g = seen.get(entry.date);
    if (!g) {
      g = { date: entry.date, items: [] };
      seen.set(entry.date, g);
      groups.push(g);
    }
    g.items.push(entry);
  }
  return groups;
}

